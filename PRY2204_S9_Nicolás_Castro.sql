CREATE TABLE REGION (
    ID_REGION        VARCHAR2(15)      NOT NULL,
    NOMBRE           VARCHAR2(60)   NOT NULL,
    CONSTRAINT PK_REGION PRIMARY KEY (ID_REGION)
);

CREATE TABLE ASOCIACION (
    ID_ASOCIACION      VARCHAR2(15)     NOT NULL,
    NOMBRE_ASOCIACION  VARCHAR2(80)  NOT NULL,
    FECHA_CREACION     DATE          NOT NULL,
    TIPO_ASOCIACION    CHAR(1)       NOT NULL,   
    CONSTRAINT PK_ASOCIACION PRIMARY KEY (ID_ASOCIACION)
);

CREATE TABLE NACIONALIDAD (
    ID_NACION    NUMBER(4)     GENERATED ALWAYS AS IDENTITY (START WITH 210 INCREMENT BY 2) NOT NULL,
    DESCRIPCION  VARCHAR2(40)  NOT NULL,
    CONSTRAINT PK_NACIONALIDAD PRIMARY KEY (ID_NACION)
);

CREATE TABLE CLUB_FUTBOL (
    ID_CLUB           NUMBER(5)      NOT NULL,   
    NOMBRE_CLUB       VARCHAR2(60)   NOT NULL,
    PATRIMONIO        NUMBER(12)     NOT NULL,   
    UBICACION_CALLE   VARCHAR2(100)  NOT NULL,
    TIPO_CLUB         VARCHAR2(20)   DEFAULT 'Profesional' NOT NULL,
    CONSTRAINT PK_CLUB_FUTBOL PRIMARY KEY (ID_CLUB)
);

CREATE TABLE ESCUELA_FUTBOL (
    ID_ESCUELA        VARCHAR2(15)      NOT NULL,
    NOMBRE_ESCUELA    VARCHAR2(60)   NOT NULL,
    CAPACIDAD         NUMBER(5)      NOT NULL,
    FECHA_FUNDACION   DATE           NOT NULL,
    CONSTRAINT PK_ESCUELA_FUTBOL PRIMARY KEY (ID_ESCUELA)
);

CREATE TABLE ESTADO_CIVIL (
    ID_ESTADO_CIVIL   VARCHAR2(15)      NOT NULL,
    DESCRIPCION       VARCHAR2(20)   NOT NULL,
    CONSTRAINT PK_ESTADO_CIVIL PRIMARY KEY (ID_ESTADO_CIVIL)
);

CREATE TABLE IDIOMA (
    ID_IDIOMA         VARCHAR2(15)      NOT NULL,
    NOMBRE_IDIOMA     VARCHAR2(40)   NOT NULL,
    CONSTRAINT PK_IDIOMA PRIMARY KEY (ID_IDIOMA)
);

--  Tablas con un nivel de dependencia 

CREATE TABLE COMUNA (
    ID_COMUNA   VARCHAR2(15)      NOT NULL,
    ID_REGION   VARCHAR2(15)      NOT NULL,
    NOMBRE      VARCHAR2(60)   NOT NULL,
    CONSTRAINT PK_COMUNA PRIMARY KEY (ID_COMUNA)
);

-- Supertipo
CREATE TABLE TRABAJADOR (
    ID_INSCRIPCION    NUMBER(9)      NOT NULL,   
    RUT_TRABAJADOR    NUMBER(8)      NOT NULL,
    DV_RUT            CHAR(1)        NOT NULL,
    NOMBRES           VARCHAR2(60)   NOT NULL,
    APELLIDOS         VARCHAR2(60)   NOT NULL,
    SUELDO_BASE       NUMBER(10)     NOT NULL,
    FECHA_NACIMIENTO  DATE           NOT NULL,
    GENERO            CHAR(1)        NOT NULL,
    ID_ESTADO_CIVIL   VARCHAR2(15)      NOT NULL,
    TELEFONO_MOVIL    VARCHAR2(15)   NOT NULL,
    EMAIL             VARCHAR2(100),
    DIRECCION         VARCHAR2(100)  NOT NULL,
    ID_COMUNA         VARCHAR2(15)      NOT NULL,
    TIPO_TRABAJADOR   CHAR(15)        NOT NULL,   
    CONSTRAINT PK_TRABAJADOR PRIMARY KEY (ID_INSCRIPCION)
);

--  Subtipos de TRABAJADOR


CREATE TABLE JUGADOR (
    ID_INSCRIPCION    NUMBER(9)      NOT NULL,
    PUESTO            VARCHAR2(30)   NOT NULL,
    MONTO_PREMIOS     NUMBER(12)     DEFAULT 0 NOT NULL,
    ID_ASOCIACION     VARCHAR2(15)      NOT NULL,
    ID_ESCUELA        VARCHAR2(15),                
    DEJA_AMATEUR      NUMBER(4),                 
    CONSTRAINT PK_JUGADOR PRIMARY KEY (ID_INSCRIPCION)
);

-- Subtipo 
CREATE TABLE PERSONAL_PLANTA (
    ID_INSCRIPCION      NUMBER(9)    NOT NULL,
    HORAS_TRABAJADAS    NUMBER(4),
    VALOR_HORA_EXTRA    NUMBER(8),
    CONSTRAINT PK_PERSONAL_PLANTA PRIMARY KEY (ID_INSCRIPCION)
);

--relaciones N:M con atributos

CREATE TABLE JUGADOR_CLUB (
    ID_INSCRIPCION        NUMBER(9)  NOT NULL,
    ID_CLUB               NUMBER(5)  NOT NULL,
    FECHA_INCORPORACION   DATE       NOT NULL,
    FECHA_FIN_CONTRATO    DATE,                 
    CONSTRAINT PK_JUGADOR_CLUB PRIMARY KEY (ID_INSCRIPCION, ID_CLUB, FECHA_INCORPORACION)
);

-- Idiomas
CREATE TABLE JUGADOR_IDIOMA (
    ID_INSCRIPCION    NUMBER(9)     NOT NULL,
    ID_IDIOMA         VARCHAR2(15)     NOT NULL,
    NIVEL_DOMINIO     VARCHAR2(15)  DEFAULT 'BASICO' NOT NULL,
    CONSTRAINT PK_JUGADOR_IDIOMA PRIMARY KEY (ID_INSCRIPCION, ID_IDIOMA)
);

-- Nacionalidades del jugador
CREATE TABLE JUGADOR_NACIONALIDAD (
    ID_INSCRIPCION    NUMBER(9)  NOT NULL,
    ID_NACION         NUMBER(4)  NOT NULL,
    CONSTRAINT PK_JUGADOR_NACIONALIDAD PRIMARY KEY (ID_INSCRIPCION, ID_NACION)
);


